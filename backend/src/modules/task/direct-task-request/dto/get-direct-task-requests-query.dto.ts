import { ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { IsEnum, IsInt, IsOptional, Min } from 'class-validator';
import { DirectTaskRequestStatus } from '@prisma/client';

export class GetDirectTaskRequestsQueryDto {
  @ApiPropertyOptional({ enum: DirectTaskRequestStatus })
  @IsOptional()
  @IsEnum(DirectTaskRequestStatus)
  status?: DirectTaskRequestStatus;

  @ApiPropertyOptional({ example: 1, default: 1 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  page?: number = 1;

  @ApiPropertyOptional({ example: 10, default: 10 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  limit?: number = 10;
}
